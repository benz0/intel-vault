"""Shared helpers for intel-vault scripts. Python 3 standard library only."""
import os
import re

BANNER = "<!-- GENERATED by intel-vault from _system/. Do not edit here; edit _system/ and re-run sync. -->"


def find_vault_root(start):
    """Walk up from start until a folder containing _system/config.md is found."""
    p = os.path.abspath(start)
    if os.path.isfile(p):
        p = os.path.dirname(p)
    while True:
        if os.path.isfile(os.path.join(p, "_system", "config.md")):
            return p
        parent = os.path.dirname(p)
        if parent == p:
            return None
        p = parent


def _strip_comment(v):
    out, q = [], None
    for i, ch in enumerate(v):
        if q:
            if ch == q:
                q = None
        elif ch in "\"'":
            q = ch
        elif ch == "#" and (i == 0 or v[i - 1] in " \t"):
            break
        out.append(ch)
    return "".join(out).strip()


def _value(v):
    v = _strip_comment(v)
    if v.startswith("[") and v.endswith("]"):
        inner = v[1:-1].strip()
        return [x.strip().strip("\"'") for x in inner.split(",") if x.strip()] if inner else []
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    return v


def read_frontmatter(path):
    """Parse flat YAML frontmatter, with one level of nesting. Returns (dict, body)."""
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    block, body = text[3:end], text[end + 4:].lstrip("\n")
    data, parent = {}, None
    for raw in block.splitlines():
        if not raw.strip() or raw.strip().startswith("#"):
            continue
        indented = raw[:1] in " \t"
        m = re.match(r"\s*([A-Za-z0-9_\-]+)\s*:\s*(.*)$", raw)
        if not m:
            continue
        key, val = m.group(1), m.group(2)
        if indented and parent is not None:
            data[parent][key] = _value(val)
            continue
        val = _value(val)
        if val == "":
            data[key] = {}
            parent = key
        else:
            data[key] = val
            parent = None
    for k, v in list(data.items()):
        if v == {}:
            data[k] = ""
    return data, body


def read_config(vault):
    cfg, _ = read_frontmatter(os.path.join(vault, "_system", "config.md"))
    return cfg


def as_list(v):
    if isinstance(v, list):
        return v
    if not v:
        return []
    return [v]


def forbidden_chars(cfg):
    """forbidden_chars: [U+2014] -> the em dash character, U+2014."""
    out = []
    for item in as_list(cfg.get("forbidden_chars")):
        m = re.fullmatch(r"[Uu]\+([0-9A-Fa-f]{4,6})", item.strip())
        out.append(chr(int(m.group(1), 16)) if m else item)
    return out


def layered(vault, sub, cfg=None):
    """Files from core, then each installed pack, then local, for a subfolder (rules or workflows).
    Returns list of (origin, path). Later entries override earlier ones with the same filename."""
    cfg = cfg or read_config(vault)
    base = os.path.join(vault, "_system")
    dirs = [("core", os.path.join(base, sub))]
    for p in as_list(cfg.get("packs")):
        dirs.append((p, os.path.join(base, "packs", p, sub)))
    dirs.append(("local", os.path.join(base, "local", sub)))
    out = []
    for origin, d in dirs:
        if os.path.isdir(d):
            for f in sorted(os.listdir(d)):
                if f.endswith(".md"):
                    out.append((origin, os.path.join(d, f)))
    return out
